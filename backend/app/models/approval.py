"""
Action approval ORM model.

Stores user approval and rejection decisions for proposed warehouse action plans
generated by the Automation Agent.
"""

from datetime import datetime, timezone
from typing import Any, Optional

from sqlalchemy import DateTime, ForeignKey, Integer, String, Text, UniqueConstraint, func, JSON
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database.base import Base


class ActionApproval(Base):
    """
    ``action_approvals`` table - stores human-in-the-loop decisions (APPROVE / REJECT)
    for proposed automation action plans.

    Attributes
    ──────────
    id              Auto-incrementing primary key.
    action_id       String ID of the action plan within the session.
    session_id      Foreign key to the discovery session.
    warehouse_id    Foreign key to the target warehouse.
    user_id         Foreign key to the approving/rejecting user.
    decision        Decision choice ('APPROVE' or 'REJECT').
    status          Resulting status ('APPROVED' or 'REJECTED').
    reason          Optional user-provided reason (e.g. for rejection).
    action_type     Type of action (e.g. 'CREATE_INDEX', 'ANALYZE_TABLE').
    target          JSON snapshot of target schema/table/column.
    risk_level      Risk classification at approval time.
    created_at      Timestamp of decision creation.
    updated_at      Timestamp of last update.
    """

    __tablename__ = "action_approvals"

    __table_args__ = (
        UniqueConstraint("action_id", "session_id", name="uq_action_session"),
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)

    action_id: Mapped[str] = mapped_column(String(64), index=True, nullable=False)

    session_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("discovery_sessions.id", ondelete="CASCADE"), index=True, nullable=False
    )

    warehouse_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("warehouses.id", ondelete="CASCADE"), index=True, nullable=False
    )

    user_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("users.id", ondelete="CASCADE"), index=True, nullable=False
    )

    decision: Mapped[str] = mapped_column(String(20), nullable=False)

    status: Mapped[str] = mapped_column(String(20), nullable=False)

    reason: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    action_type: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)

    target: Mapped[Optional[Any]] = mapped_column(JSON().with_variant(JSONB, "postgresql"), nullable=True)

    risk_level: Mapped[Optional[str]] = mapped_column(String(20), nullable=True)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), server_default=func.now(), nullable=False
    )

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        server_default=func.now(),
        nullable=False,
    )

    # ── Relationships ─────────────────────────────────────────────

    session: Mapped["DiscoverySession"] = relationship("DiscoverySession")  # noqa: F821
    warehouse: Mapped["Warehouse"] = relationship("Warehouse")  # noqa: F821
    user: Mapped["User"] = relationship("User")  # noqa: F821

    def __repr__(self) -> str:
        return (
            f"<ActionApproval(id={self.id}, action_id={self.action_id!r}, "
            f"decision={self.decision!r}, user_id={self.user_id})>"
        )
